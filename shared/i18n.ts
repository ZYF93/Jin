const dictionaries: Record<Language, Record<MessageKey, string>> = { en, zh };

export type TranslationParams = Record<string, string | number | undefined>;

/** True when a value is one of the supported interface languages. */
export function isLanguage(value: unknown): value is Language {
  return value === "en" || value === "zh";
}

export function translate(
  language: Language,
  key: MessageKey,
  params: TranslationParams = {},
): string {
  const dictionary = dictionaries[language] ?? en;
  const raw = dictionary[key] ?? en[key] ?? key;
  const forms = raw.split("|");
  const count = typeof params.count === "number" ? params.count : 1;
  const template = forms.length > 1 ? (count === 1 ? forms[0] : forms[1]) : raw;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}
