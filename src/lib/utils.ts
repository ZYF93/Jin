/** Localized approval-risk copy. Unknown future hints keep their stored text. */
export function riskText(
  risk: RiskHint,
  diff: ArchDiff | null,
  t: Translator,
): { title: string; detail: string } {
  if (!diff) return { title: risk.title, detail: risk.detail };
  const total = diff.summary.added + diff.summary.removed + diff.summary.modified;
  switch (risk.id) {
    case "risk:removals":
      return {
        title: t("risk.removals.title", { count: diff.summary.removed }),
        detail: t("risk.removals.detail"),
      };
    case "risk:system":
      return { title: t("risk.system.title"), detail: t("risk.system.detail") };
    case "risk:moves":
      return { title: t("risk.moves.title"), detail: t("risk.moves.detail") };
    case "risk:blast-radius":
      return {
        title: t("risk.blastRadius.title"),
        detail: t("risk.blastRadius.detail", {
          total,
          affected: diff.summary.affected,
        }),
      };
    case "risk:blast-radius-medium":
      return {
        title: t("risk.blastRadiusMedium.title"),
        detail: t("risk.blastRadiusMedium.detail", {
          total,
          affected: diff.summary.affected,
        }),
      };
    case "risk:responsibility": {
      const count = Object.values(diff.nodes).filter((change) => {
        const node = change.after ?? change.before;
        return node?.level === "L1" && !node.responsibility.trim();
      }).length;
      return {
        title: t("risk.responsibility.title"),
        detail: t("risk.responsibility.detail", { count }),
      };
    }
    case "risk:remove-children":
      return {
        title: t("risk.removeChildren.title"),
        detail: t("risk.removeChildren.detail"),
      };
    case "risk:contained":
      return {
        title: t("risk.contained.title"),
        detail: t("risk.contained.detail"),
      };
    default:
      return { title: risk.title, detail: risk.detail };
  }
}

/** Translate the reuse-plan summary generated by the main process. */
export function localizeReuseSummary(summary: string, t: Translator): string {
  const found = /^Found (\d+) existing unit(?:s)? worth reusing before writing new code\.$/.exec(
    summary,
  );
  if (found) return t("reuse.summaryFound", { count: Number(found[1]) });
  if (
    summary ===
    "No close existing implementation found; new code may be justified, but explain why reuse is not possible."
  ) {
    return t("reuse.summaryNone");
  }
  return summary;
}

/** Translate the generated reuse reason; source responsibilities stay verbatim. */
export function localizeReuseReason(reason: string, t: Translator): string {
  const match = /^Matches (.*) in the scanned source\.$/.exec(reason);
  if (match) return t("reuse.reasonMatches", { terms: match[1] });
  return reason;
}

const CHECK_NAME_KEYS: Record<string, MessageKey> = {
  "architecture conformance": "verify.architectureConformance",
  "project checks": "verify.projectChecks",
  reuse: "verify.reuseCheck",
  "language diagnostics": "verify.languageDiagnostics",
};

/** Translate fixed built-in implementation-check names, leaving script names alone. */
export function localizeCheckName(name: string, t: Translator): string {
  const key = CHECK_NAME_KEYS[name.toLowerCase()];
  return key ? t(key) : name;
}

/** Translate conformance evidence written by older and current main processes. */
export function localizeEvidence(evidence: string, t: Translator): string {
  if (evidence === "No architecture drift detected between approved L0/L1 nodes and source scan") {
    return t("verify.driftClean");
  }
  let match = /^Observed source file (.*)$/.exec(evidence);
  if (match) return t("verify.sourceObserved", { file: match[1] });
  match = /^Source file (.*) was not observed$/.exec(evidence);
  if (match) return t("verify.sourceMissing", { file: match[1] });
  match = /^Observed (L0|L1) (.*) at (.*)$/.exec(evidence);
  if (match) {
    return t("verify.nodeObserved", {
      level: match[1],
      name: match[2],
      path: match[3],
    });
  }
  match = /^Not observed in a fresh scan: (L0|L1) (.*) \((.*)\)$/.exec(evidence);
  if (match) {
    return t("verify.nodeMissing", {
      level: match[1],
      name: match[2],
      path: match[3],
    });
  }
  match = /^Observed updated node (.*) at (.*)$/.exec(evidence);
  if (match) return t("verify.updatedObserved", { name: match[1], path: match[2] });
  match = /^Facet (.*) mapped to observed file (.*)$/.exec(evidence);
  if (match) return t("verify.facetObserved", { name: match[1], file: match[2] });
  match = /^Updated node (.*) was not observed$/.exec(evidence);
  if (match) return t("verify.updatedMissing", { id: match[1] });
  match = /^Removed node (.*) is still present in source facts$/.exec(evidence);
  if (match) return t("verify.removedPresent", { name: match[1] });
  match = /^Removed node (.*) is no longer observed$/.exec(evidence);
  if (match) return t("verify.removedGone", { name: match[1] });
  match = /^Structural (.*) is declared in the approved snapshot$/.exec(evidence);
  if (match) return t("verify.structural", { op: match[1] });
  match = /^Undeclared source node (.*)$/.exec(evidence);
  if (match) return t("verify.undeclared", { id: match[1] });
  match = /^Declared node (.*) has no source fact$/.exec(evidence);
  if (match) return t("verify.declaredMissing", { id: match[1] });
  return evidence;
}

/** Translate fixed project-check skip/pass details; command output stays verbatim. */
export function localizeCheckDetail(detail: string, t: Translator): string {
  if (detail === "No package.json found; no project test/typecheck scripts to run.") {
    return t("verify.noPackage");
  }
  if (detail === "No typecheck/test/lint scripts found in package.json.") {
    return t("verify.noScripts");
  }
  if (detail === "package.json is not valid JSON.") {
    return t("verify.invalidPackage");
  }
  if (detail === "Passed") return t("verify.passed");
  if (detail === "No close reuse candidate was found; new code is allowed.") {
    return t("verify.reuseNoCandidate");
  }
  let match = /^Reused or updated candidate file\(s\): (.*)\.$/.exec(detail);
  if (match) return t("verify.reuseTouched", { paths: match[1] });
  match =
    /^New exports duplicate existing units: (.*)\. Reuse or rename them before committing\.$/.exec(
      detail,
    );
  if (match) return t("verify.reuseDuplicate", { paths: match[1] });
  match =
    /^ReusePlan listed (\d+) candidate\(s\) \((.*)\), but the implementation changed none\. Verify that new code does not duplicate them\.$/.exec(
      detail,
    );
  if (match) {
    return t("verify.reuseSkipped", {
      count: Number(match[1]),
      paths: match[2],
    });
  }
  if (detail === "Timed out") return t("verify.timedOut");
  if (detail.startsWith("Timed out\n")) {
    return `${t("verify.timedOut")}\n${detail.slice("Timed out\n".length)}`;
  }
  return detail;
}

export function errorMessage(error: unknown): string {
  if (error instanceof Error && error.message) return error.message;
  const text = String(error);
  return text === "[object Object]" ? t("error.unexpected") : text;
}

export function formatDate(value: string | null | undefined): string {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(localeTag(), {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

export function formatTime(value: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat(localeTag(), {
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

export function formatRelative(value: string | null | undefined): string {
  if (!value) return t("common.never");
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return t("common.never");
  const seconds = Math.round((date.getTime() - Date.now()) / 1000);
  const formatter = new Intl.RelativeTimeFormat(localeTag(), { numeric: "auto" });
  if (Math.abs(seconds) < 60) return formatter.format(seconds, "second");
  const minutes = Math.round(seconds / 60);
  if (Math.abs(minutes) < 60) return formatter.format(minutes, "minute");
  const hours = Math.round(minutes / 60);
  if (Math.abs(hours) < 24) return formatter.format(hours, "hour");
  return formatter.format(Math.round(hours / 24), "day");
}

export function formatCount(value: number): string {
  return new Intl.NumberFormat(localeTag(), { notation: "compact" }).format(value);
}

export function formatDuration(ms: number | null | undefined): string {
  if (ms === null || ms === undefined || !Number.isFinite(ms)) return "—";
  if (ms < 1_000) return `${Math.round(ms)}ms`;
  const seconds = ms / 1_000;
  if (seconds < 60) return `${seconds < 10 ? seconds.toFixed(1) : Math.round(seconds)}s`;
  const minutes = seconds / 60;
  if (minutes < 60) return `${minutes < 10 ? minutes.toFixed(1) : Math.round(minutes)}m`;
  const hours = Math.floor(minutes / 60);
  const rest = Math.round(minutes % 60);
  return rest > 0 ? `${hours}h ${rest}m` : `${hours}h`;
}

export function formatRate(rate: number | null | undefined): string {
  if (rate === null || rate === undefined || !Number.isFinite(rate)) return "—";
  return new Intl.NumberFormat(localeTag(), {
    style: "percent",
    maximumFractionDigits: 0,
  }).format(rate);
}

export function formatCost(value: number, priced: boolean): string {
  if (!priced) return t("common.unpriced");
  if (value <= 0) return "$0";
  if (value < 0.01) return `$${value.toFixed(4)}`;
  if (value < 1) return `$${value.toFixed(3)}`;
  return `$${value.toFixed(2)}`;
}

export function formatCountLabel(
  value: number,
  singular: string,
  plural = `${singular}s`,
): string {
  return `${formatCount(value)} ${value === 1 ? singular : plural}`;
}

export function formatBytes(value: number | undefined): string {
  if (!value) return "0 B";
  const units = ["B", "KB", "MB", "GB"];
  let size = value;
  let unit = 0;
  while (size >= 1024 && unit < units.length - 1) {
    size /= 1024;
    unit += 1;
  }
  return `${size >= 10 || unit === 0 ? Math.round(size) : size.toFixed(1)} ${units[unit]}`;
}

export function versionOrdinal(
  snapshot: ArchSnapshot | null | undefined,
  versionId: string,
): number | null {
  return snapshot?.versions[versionId]?.ordinal ?? null;
}

export function nextOrdinal(snapshot: ArchSnapshot | null | undefined): number {
  if (!snapshot) return 1;
  let max = 0;
  for (const version of Object.values(snapshot.versions)) {
    if (version.ordinal !== null) max = Math.max(max, version.ordinal);
  }
  return max + 1;
}

export function ordinalLabel(ordinal: number | null | undefined): string {
  return ordinal ? `v${ordinal}` : "v—";
}

export function isReviewing(proposal: ProposalView | null | undefined): boolean {
  return proposal?.status === "in_review" || proposal?.status === "stale";
}

export function changeLabel(change: ChangeKind | undefined): string {
  if (change === "added") return t("change.added");
  if (change === "removed") return t("change.removed");
  if (change === "modified") return t("change.modified");
  return t("change.unchanged");
}

export function statusLabel(status: VersionStatus): string {
  const keys: Record<VersionStatus, MessageKey> = {
    draft: "status.draft",
    in_review: "status.in_review",
    approved: "status.approved",
    rejected: "status.rejected",
    implemented: "status.implemented",
    verified: "status.verified",
    superseded: "status.superseded",
    conflicted: "status.conflicted",
  };
  const key = keys[status];
  return key ? t(key) : status;
}

export function nodeStatusLabel(status: NodeStatus): string {
  const keys: Record<NodeStatus, MessageKey> = {
    active: "nodeStatus.active",
    planned: "nodeStatus.planned",
    deprecated: "nodeStatus.deprecated",
  };
  return t(keys[status] ?? "nodeStatus.active");
}

export function statusTone(
  status: VersionStatus,
): "muted" | "accent" | "success" | "warning" | "danger" {
  switch (status) {
    case "approved":
    case "implemented":
    case "verified":
      return "success";
    case "in_review":
    case "draft":
      return "accent";
    case "conflicted":
      return "danger";
    case "rejected":
      return "muted";
    default:
      return "muted";
  }
}

